LON, LAT = np.meshgrid(lon, lat)

land = globe.is_land(LAT, LON)


def seg_dist(points, w):
    """Distance (degrees, longitude scaled by latitude) from every pixel to a polyline."""
    d = np.full(LAT.shape, 1e9)
    for (la1, lo1), (la2, lo2) in zip(points[:-1], points[1:]):
        k = np.cos(np.radians((la1 + la2) / 2))
        ax, ay = lo1 * k, la1
        bx, by = lo2 * k, la2
        px, py = LON * k, LAT
        vx, vy = bx - ax, by - ay
        ll = vx * vx + vy * vy + 1e-9
        t = np.clip(((px - ax) * vx + (py - ay) * vy) / ll, 0, 1)
        dx, dy = px - (ax + t * vx), py - (ay + t * vy)
        d = np.minimum(d, np.sqrt(dx * dx + dy * dy))
    return d / w


def ellipse(la, lo, rx, ry):
    return np.sqrt(((LON - lo) / rx) ** 2 + ((LAT - la) / ry) ** 2)


