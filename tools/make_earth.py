"""Builds the data for the "Earth" game mode.

Writes data/earth.png (RGBA, 1440 x 544, equirectangular, 80N..56S, 0.25 degree pixels):
  R: 0..99 water (0 = deep ocean, 99 = shallow coast), 100..255 land height
  G: moisture 0..255
  B: temperature, (deg C + 30) * 4
  A: 255
and data/earth.json with the major rivers as [lat, lon] polylines.

Land comes from the global-land-mask package (pip install global-land-mask); mountains, deserts,
rainforests, big lakes and rivers are hand-placed from an atlas, so the biomes line up roughly
with the real world.  Usage: python3 tools/make_earth.py data
"""
